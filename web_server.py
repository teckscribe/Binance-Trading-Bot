def _asset_version() -> str:
    """
    Cache-busting token derived from the newest mtime across app.js/style.css.

    Without this the browser keeps serving a cached app.js after a deploy, so
    UI changes silently do not appear (the page renders new HTML driven by old
    JS). Recomputed per request so a redeploy invalidates immediately.
    """
    newest = 0.0
    for name in ("app.js", "style.css"):
        path = os.path.join(STATIC_DIR, name)
        try:
            newest = max(newest, os.path.getmtime(path))
        except OSError:
            continue
    return str(int(newest))


@app.get("/")
async def serve_index():
    index_file = os.path.join(STATIC_DIR, "index.html")
    if os.path.exists(index_file):
        try:
            with open(index_file, "r", encoding="utf-8") as f:
                html = f.read()
            return HTMLResponse(html.replace("__ASSETV__", _asset_version()))
        except Exception:
            # Fall back to the raw file rather than 500 on a read/encoding error
            return FileResponse(index_file)
    return {"message": "CSB Web API is online."}

