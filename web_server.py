_SPEC_BY_KEY = {e["key"]: e for e in SETTINGS_SPEC}


def _read_env_values() -> dict:
    """Current values for spec keys ONLY. Never returns anything else."""
    out = {}
    try:
        with open(ENV_FILE, encoding="utf-8", errors="replace") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or "=" not in line:
                    continue
                k, v = line.split("=", 1)
                k = k.strip()
                if k in _SPEC_BY_KEY:
                    out[k] = v.strip()
    except Exception as exc:
        log.error(f"settings: cannot read .env: {exc}")
    return out


def _validate(spec: dict, raw) -> tuple:
    """Returns (ok, normalised_string, error).

    Server-side and authoritative — the browser's input types are a convenience
    for the operator, never a guarantee about what arrives here.
    """
    t = spec["type"]
    key = spec["key"]
    s = str(raw).strip()
    if s == "":
        return False, "", f"{key}: value required"

    if t == "bool":
        if s.lower() in ("true", "1", "yes", "on"):
            return True, "true", ""
        if s.lower() in ("false", "0", "no", "off"):
            return True, "false", ""
        return False, "", f"{key}: expected true or false"

    if t == "choice":
        for opt in spec["options"]:
            if s.lower() == opt.lower():
                return True, opt, ""
        return False, "", f"{key}: must be one of {', '.join(spec['options'])}"

    if t in ("int", "float"):
        try:
            v = int(s) if t == "int" else float(s)
        except ValueError:
            return False, "", f"{key}: not a valid {t}"
        lo, hi = spec.get("min"), spec.get("max")
        if lo is not None and v < lo:
            return False, "", f"{key}: below minimum {lo}"
        if hi is not None and v > hi:
            return False, "", f"{key}: above maximum {hi}"
        return True, (str(v) if t == "int" else str(round(v, 6))), ""

    if t == "csv_caps":
        # STRATEGY:int,... — a malformed value here silently disables every
        # per-strategy cap, so it is parsed strictly rather than trusted.
        parts = [p for p in s.split(",") if p.strip()]
        if not parts:
            return False, "", f"{key}: empty"
        clean = []
        for part in parts:
            if ":" not in part:
                return False, "", f"{key}: '{part}' is not STRATEGY:N"
            name, num = part.split(":", 1)
            name, num = name.strip().upper(), num.strip()
            if not re.fullmatch(r"[A-Z0-9_]+", name):
                return False, "", f"{key}: bad strategy name '{name}'"
            if not num.isdigit() or int(num) > 20:
                return False, "", f"{key}: '{name}' cap must be 0-20"
            clean.append(f"{name}:{int(num)}")
        return True, ",".join(clean), ""

    return False, "", f"{key}: unknown type {t}"


def _write_env_values(updates: dict) -> tuple:
    """Rewrite .env in place, preserving comments, order and formatting.

    Only lines whose key appears in `updates` are touched. The new content is
    written to a temp file in the same directory and then atomically replaced,
    so an interrupted or failing write cannot leave a truncated .env — the exact
    failure a plain open(path, "w") produced when an encoding error hit AFTER
    truncation.
    """
    tmp = None
    try:
        with open(ENV_FILE, encoding="utf-8", errors="replace") as f:
            lines = f.read().splitlines(keepends=True)
    except Exception as exc:
        return False, f"cannot read .env: {exc}"

    nl = "\r\n" if (lines and lines[0].endswith("\r\n")) else "\n"
    remaining = dict(updates)
    out = []
    for line in lines:
        stripped = line.strip()
        if stripped and not stripped.startswith("#") and "=" in stripped:
            k = stripped.split("=", 1)[0].strip()
            if k in remaining:
                out.append(f"{k}={remaining.pop(k)}{nl}")
                continue
        out.append(line)
    for k, v in remaining.items():          # key not present in the file yet
        if out and not out[-1].endswith("\n"):
            out.append(nl)
        out.append(f"{k}={v}{nl}")

    try:
        fd, tmp = tempfile.mkstemp(dir=os.path.dirname(ENV_FILE) or ".",
                                   prefix=".env.", suffix=".tmp")
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as f:
            f.writelines(out)
        os.replace(tmp, ENV_FILE)
    except Exception as exc:
        if tmp:
            try:
                os.unlink(tmp)
            except Exception:
                pass
        return False, f"cannot write .env: {exc}"
    return True, ""


def _totp_configured() -> bool:
    return bool(pyotp) and bool((os.getenv("DASHBOARD_TOTP_SECRET") or "").strip())


def _check_otp(code: str) -> tuple:
    """Verify a Google Authenticator code, with lockout on repeated failure."""
    now = time.time()
    if _otp_failures["locked_until"] > now:
        wait = int(_otp_failures["locked_until"] - now)
        return False, f"Too many incorrect codes. Try again in {wait}s."
    if not _totp_configured():
        return False, ("Editing is disabled: no DASHBOARD_TOTP_SECRET is set. "
                       "Run dashboard_2fa_setup.py on the server.")
    code = (code or "").strip().replace(" ", "")
    if not code.isdigit() or len(code) != 6:
        return False, "Enter the 6-digit code from Google Authenticator."

    secret = (os.getenv("DASHBOARD_TOTP_SECRET") or "").strip()
    try:
        # valid_window=1 tolerates one 30s step of clock drift either way.
        ok = pyotp.TOTP(secret).verify(code, valid_window=1)
    except Exception as exc:
        log.error(f"settings: TOTP verify failed: {exc}")
        return False, "Two-factor verification is misconfigured on the server."

    if ok:
        _otp_failures["count"] = 0
        return True, ""

    _otp_failures["count"] += 1
    if _otp_failures["count"] >= _OTP_MAX_FAILURES:
        _otp_failures["locked_until"] = now + _OTP_LOCKOUT_SECONDS
        _otp_failures["count"] = 0
        log.warning("[SETTINGS] TOTP lockout triggered after repeated failures")
        return False, (f"Too many incorrect codes. Locked for "
                       f"{_OTP_LOCKOUT_SECONDS // 60} minutes.")
    return False, "Incorrect code."


@app.get("/api/settings")
async def get_settings():
    """Editable settings and their current values.

    Secrets are absent from SETTINGS_SPEC and therefore never reach this
    response, regardless of what is in .env.
    """
    values = _read_env_values()
    fields = []
    for spec in SETTINGS_SPEC:
        f = dict(spec)
        f["value"] = values.get(spec["key"], "")
        f["present"] = spec["key"] in values
        fields.append(f)
    configured = _totp_configured()
    if configured:
        reason = ""
    elif not pyotp:
        reason = ("Read-only: pyotp is not installed on the server "
                  "(pip install pyotp).")
    else:
        reason = ("Read-only: two-factor is not set up. Run "
                  "dashboard_2fa_setup.py on the server, scan the code "
                  "with Google Authenticator, then restart the dashboard.")
    return {
        "fields": fields,
        "editable": configured,
        "reason": reason,
        "excluded_note": ("API keys, bot tokens, webhooks and LIVE_ENABLED are "
                          "deliberately not editable from this page."),
    }


@app.post("/api/settings")
async def save_settings(request: Request):
    try:
        body = await request.json()
    except Exception:
        return JSONResponse({"ok": False, "error": "invalid JSON"},
                            status_code=400)

    ok, why = _check_otp(body.get("otp", ""))
    if not ok:
        return JSONResponse({"ok": False, "error": why}, status_code=403)

    changes = body.get("changes")
    if not isinstance(changes, dict) or not changes:
        return JSONResponse({"ok": False, "error": "no changes supplied"},
                            status_code=400)

    current = _read_env_values()
    updates, errors, applied = {}, [], []
    for key, raw in changes.items():
        spec = _SPEC_BY_KEY.get(key)
        if spec is None:
            # Never silently ignored — an unknown key means the client and the
            # server disagree about what is editable, which is worth surfacing.
            errors.append(f"{key}: not an editable setting")
            continue
        good, norm, err = _validate(spec, raw)
        if not good:
            errors.append(err)
            continue
        if current.get(key) != norm:
            updates[key] = norm
            applied.append({"key": key, "from": current.get(key, ""),
                            "to": norm})

    if errors:
        return JSONResponse({"ok": False, "error": "; ".join(errors)},
                            status_code=400)
    if not updates:
        return {"ok": True, "applied": [], "restart_required": False,
                "message": "No changes — values already match."}

    wrote, err = _write_env_values(updates)
    if not wrote:
        return JSONResponse({"ok": False, "error": err}, status_code=500)

    for a in applied:
        log.info(f"[SETTINGS] {a['key']}: {a['from']!r} -> {a['to']!r}")
    restart = any(_SPEC_BY_KEY[a["key"]].get("restart") for a in applied)
    plural = "" if len(applied) == 1 else "s"
    return {
        "ok": True,
        "applied": applied,
        "restart_required": restart,
        "message": (f"Saved {len(applied)} setting{plural}."
                    + (" Restart the scanner to apply." if restart else "")),
    }


SQUARE_OFF_FILE = os.path.join(DATA_DIR, "square_off_queue.json")


@app.post("/api/square_off")
async def square_off(request: Request):
    """
    Queue a position for immediate close by the live scanner.

    The web server cannot close positions directly (it has no access to the
    OrderEngine or Binance credentials). Instead it writes the request to
    data/square_off_queue.json, which the live scanner checks at the top of
    every cycle (~5s) and executes via its normal close_position path.
    """
    body = await request.json()
    symbol = body.get("symbol", "").strip().upper()
    direction = body.get("direction", "").strip().upper()

    if not symbol or direction not in ("LONG", "SHORT"):
        return JSONResponse({"ok": False, "error": "symbol and direction required"},
                            status_code=400)

    queue = []
    if os.path.exists(SQUARE_OFF_FILE):
        try:
            with open(SQUARE_OFF_FILE, "r") as f:
                queue = json.load(f)
        except Exception:
            queue = []

    already = any(r["symbol"] == symbol and r["direction"] == direction for r in queue)
    if already:
        return {"ok": True, "status": "already_queued"}

    queue.append({
        "symbol": symbol,
        "direction": direction,
        "requested_at": datetime.utcnow().isoformat(),
        "source": "web_dashboard",
    })

    os.makedirs(DATA_DIR, exist_ok=True)
    with open(SQUARE_OFF_FILE, "w") as f:
        json.dump(queue, f)

    return {"ok": True, "status": "queued"}


