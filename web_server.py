@app.post("/api/settings")
async def save_settings(request: Request):
    try:
        body = await request.json()
    except Exception:
        return JSONResponse({"ok": False, "error": "invalid JSON"},
                            status_code=400)

    ok, why = _check_otp(body.get("otp", ""))
    if not ok:
        return JSONResponse({"ok": False, "error": why}, status_code=403)

    changes = body.get("changes")
    if not isinstance(changes, dict) or not changes:
        return JSONResponse({"ok": False, "error": "no changes supplied"},
                            status_code=400)

    # Never silently ignored — an unknown key means the client and the
    # server disagree about what is editable, which is worth surfacing.
    unknown = [k for k in changes if k not in _SPEC_BY_KEY]
    if unknown:
        return JSONResponse(
            {"ok": False, "error": "; ".join(f"{k}: not an editable setting"
                                             for k in unknown)},
            status_code=400)

    ok, applied, errors = cfg.update(changes, source="dashboard")
    if errors:
        status = 500 if errors == ["could not write settings.json"] else 400
        return JSONResponse({"ok": False, "error": "; ".join(errors)},
                            status_code=status)
    if not applied:
        return {"ok": True, "applied": [], "restart_required": False,
                "message": "No changes — values already match."}

    cold = [a["key"] for a in applied if not cfg.is_hot(a["key"])]
    plural = "" if len(applied) == 1 else "s"
    if cold:
        note = (f" {', '.join(cold)} take{'s' if len(cold) == 1 else ''} "
                f"effect on the next service restart; everything else is live.")
    else:
        note = " The scanner applies them on its next cycle — no restart needed."
    return {
        "ok": True,
        "applied": applied,
        "restart_required": bool(cold),
        "message": f"Saved {len(applied)} setting{plural}.{note}",
    }


SQUARE_OFF_FILE = os.path.join(DATA_DIR, "square_off_queue.json")


@app.post("/api/square_off")
async def square_off(request: Request):
    """
    Queue a position for immediate close by the live scanner.

    The web server cannot close positions directly (it has no access to the
    OrderEngine or Binance credentials). Instead it writes the request to
    data/square_off_queue.json, which the live scanner checks at the top of
    every cycle (~5s) and executes via its normal close_position path.
    """
    body = await request.json()
    symbol = body.get("symbol", "").strip().upper()
    direction = body.get("direction", "").strip().upper()

    if not symbol or direction not in ("LONG", "SHORT"):
        return JSONResponse({"ok": False, "error": "symbol and direction required"},
                            status_code=400)

    queue = []
    if os.path.exists(SQUARE_OFF_FILE):
        try:
            with open(SQUARE_OFF_FILE, "r") as f:
                queue = json.load(f)
        except Exception:
            queue = []

    already = any(r["symbol"] == symbol and r["direction"] == direction for r in queue)
    if already:
        return {"ok": True, "status": "already_queued"}

    queue.append({
        "symbol": symbol,
        "direction": direction,
        "requested_at": datetime.utcnow().isoformat(),
        "source": "web_dashboard",
    })

    os.makedirs(DATA_DIR, exist_ok=True)
    with open(SQUARE_OFF_FILE, "w") as f:
        json.dump(queue, f)

    return {"ok": True, "status": "queued"}


