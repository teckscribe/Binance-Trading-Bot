@app.get("/api/strategies")
async def get_strategies():
    """
    The strategies actually loaded by the engine and whether each one can
    currently take a trade.

    Four states, narrowest cause first:
      DISABLED  manually switched off via Telegram/Discord (strategy_overrides)
      OFF       permitted in NO regime — turned off by config, not by market
      IDLE      permitted somewhere, but not in the regime running right now
      ACTIVE    permitted in the current regime and able to fire
    """
    try:
        from modules.strategies.strategy_factory import StrategyFactory
        ids = [s.STRATEGY_ID for s in StrategyFactory.get_all()]
    except Exception as exc:
        return {"strategies": [], "error": f"factory unavailable: {exc}"}

    try:
        from modules.strategy_overrides import is_disabled
    except Exception:
        def is_disabled(_):
            return False

    try:
        from modules.regime_engine import REGIME_STRATEGY_PERMISSIONS as _PERMS
    except Exception:
        _PERMS = {}

    # Regime the scanner last reported. Falling back to UNKNOWN keeps a
    # permitted strategy out of ACTIVE rather than claiming it is live.
    regime = "UNKNOWN"
    state_file = os.path.join(DATA_DIR, "active_state.json")
    if os.path.exists(state_file):
        try:
            with open(state_file, "r") as f:
                regime = json.load(f).get("regime", "UNKNOWN") or "UNKNOWN"
        except Exception:
            pass

    out = []
    for sid in ids:
        name, tier, desc, colour = _STRATEGY_META.get(
            sid, (sid, "Unknown", "No description registered", "#94A3B8"))

        permitted_in = sorted(r for r, m in _PERMS.items() if m.get(sid, False))

        if is_disabled(sid):
            status = "DISABLED"
        elif not permitted_in:
            status = "OFF"
        elif regime in permitted_in:
            status = "ACTIVE"
        else:
            status = "IDLE"

        out.append({
            "id": sid, "name": name, "tier": tier, "desc": desc,
            "colour": colour,
            "status": status,
            "permitted_in": permitted_in,
        })

    return {
        "strategies": out,
        "count": len(out),
        "regime": regime,
        "active": sum(1 for s in out if s["status"] == "ACTIVE"),
    }


@app.get("/api/trades")
async def get_recent_trades():
    """Reads recent closed trades from the live JSONL logs."""
    trades = []
    # Find the most recent session JSON file
    session_files = sorted(glob.glob(os.path.join(LOGS_DIR, "session_*.json")))
    if not session_files:
        return {"trades": []}

    # Session logs are a single pretty-printed JSON object with a "trades"
    # array — not JSONL. This previously read them line-by-line and filtered on
    # record["event"] == "TRADE_EXIT", but live_logger writes "type": "EXIT",
    # so every line failed to parse and the endpoint always returned empty.
    for file in session_files[-3:]:
        try:
            with open(file, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            continue
        if isinstance(data, dict):
            trades.extend(t for t in data.get("trades", []) if isinstance(t, dict))

    # Sort by exit time descending. live_logger stamps each record as "time".
    trades.sort(key=lambda x: x.get("time", x.get("timestamp", "")), reverse=True)
    return {"trades": trades[:50]}


# ─── Performance analytics ───────────────────────────────────────────────────

def _load_all_trades() -> list:
    """Every closed trade across every session log, oldest first."""
    out = []
    for path in sorted(glob.glob(os.path.join(LOGS_DIR, "session_*.json"))):
        try:
            with open(path, "r", encoding="utf-8") as f:
                data = json.load(f)
        except Exception:
            continue
        if isinstance(data, dict):
            out.extend(t for t in data.get("trades", []) if isinstance(t, dict))
    out.sort(key=lambda t: t.get("time", ""))
    return out


def _current_period(trades: list) -> tuple:
    """
    Narrow `trades` to the equity period the wallet balance is measuring.

    The Performance tab used to sum EVERY session log on disk while the wallet
    balance tracked only trades since paper_equity.json was last reset. With
    152 logged trades against 18 in the current period, the tab showed +$8.57
    directly above a wallet of $95.75 — both correct, visibly contradictory.

    Two ways to find the boundary, in order of reliability:
      1. `period_start` written by paper_equity._blank() on reset.
      2. Fall back to the most recent N trades, N = the tracker's trade count.
         Older state files predate `period_start`; this keeps them working,
         but it drifts if a close ever failed to reach the session log.

    Returns (scoped_trades, meta).
    """
    state_file = os.path.join(DATA_DIR, "paper_equity.json")
    try:
        with open(state_file, "r", encoding="utf-8") as f:
            eq = json.load(f)
    except Exception:
        return trades, {"scope": "all", "reason": "no paper_equity.json"}

    start = eq.get("period_start")
    count = int(eq.get("trades", 0) or 0)

    if start:
        scoped = [t for t in trades if str(t.get("time", "")) >= str(start)]
        return scoped, {"scope": "period", "period_start": start,
                        "basis": "period_start"}

    if count and count < len(trades):
        # No period_start (pre-existing state file) — take the newest N.
        scoped = trades[-count:]
        return scoped, {"scope": "period", "basis": "trade_count",
                        "period_start": scoped[0].get("time") if scoped else None}

    return trades, {"scope": "all", "reason": "period covers all logged trades"}


# Below this many trades, win rate / profit factor / top-trade share are noise
# and the UI shows "—" instead of a number. See _stats().
MIN_SAMPLE_FOR_RATIOS = 5


def _stats(trades: list) -> dict:
    """
    Win rate, profit factor and expectancy for a group of trades.

    Profit factor (gross wins / gross losses) is the headline: a strategy can
    win 67% of the time and still be unprofitable if one outlier carries it,
    which is why `top_trade_share` is reported alongside — it shows how much of
    the gross profit rests on the single best trade.
    """
    n = len(trades)
    if not n:
        return {"trades": 0, "wins": 0, "win_rate": 0.0, "net": 0.0,
                "profit_factor": 0.0, "avg_win": 0.0, "avg_loss": 0.0,
                "expectancy": 0.0, "top_trade_share": 0.0, "sample_ok": False}

    nets = [float(t.get("pnl_usdt_net", 0.0)) for t in trades]
    wins = [v for v in nets if v > 0]
    losses = [v for v in nets if v <= 0]
    gross_w = sum(wins)
    gross_l = abs(sum(losses))
    net = sum(nets)

    return {
        # Ratio stats are meaningless on a handful of trades, and rendering them
        # anyway actively misleads: one losing trade in a fresh equity period
        # showed "0% win rate / PF 0.00" directly above an all-time line reading
        # +$1.00, which reads as a broken bot rather than a 1-trade sample.
        # The UI dashes them out below this threshold; counts and sums, which are
        # literal facts about the sample, are always shown.
        "sample_ok": n >= MIN_SAMPLE_FOR_RATIOS,
        "trades": n,
        "wins": len(wins),
        "win_rate": round(len(wins) / n * 100, 1),
        "net": round(net, 4),
        "profit_factor": round(gross_w / gross_l, 2) if gross_l else None,
        "avg_win": round(gross_w / len(wins), 4) if wins else 0.0,
        "avg_loss": round(-gross_l / len(losses), 4) if losses else 0.0,
        "expectancy": round(net / n, 4),
        # Share of gross profit from the single best trade — an outlier
        # dependency warning. High values mean the edge is not broad.
        "top_trade_share": round(max(wins) / gross_w * 100, 1) if wins else 0.0,
    }


@app.get("/api/performance")
async def get_performance():
    """
    Aggregate trade analytics: overall, per strategy, per symbol, per exit
    reason, plus a cumulative equity curve. Per-symbol is sorted worst-first
    so blacklist candidates surface immediately.
    """
    all_trades = _load_all_trades()
    if not all_trades:
        return {"overall": _stats([]), "by_strategy": [], "by_symbol": [],
                "by_exit": [], "equity_curve": [], "generated": None,
                "alltime": _stats([]), "period": {"scope": "all"}}

    # Scope to the current equity period so this agrees with the wallet balance.
    trades, period = _current_period(all_trades)
    period["trades_in_period"] = len(trades)
    period["trades_all_time"]  = len(all_trades)

    def group(key):
        buckets = {}
        for t in trades:
            buckets.setdefault(t.get(key, "?"), []).append(t)
        return buckets

    by_strategy = [
        {"name": k, **_stats(v)} for k, v in group("strategy").items()
    ]
    by_strategy.sort(key=lambda r: r["net"], reverse=True)

    by_symbol = [
        {"name": k, **_stats(v)} for k, v in group("symbol").items()
    ]
    by_symbol.sort(key=lambda r: r["net"])          # worst first = blacklist list

    by_exit = []
    for k, v in group("exit_reason").items():
        nets = [float(t.get("pnl_usdt_net", 0.0)) for t in v]
        by_exit.append({
            "name": k, "trades": len(v),
            "share": round(len(v) / len(trades) * 100, 1),
            "net": round(sum(nets), 4),
        })
    by_exit.sort(key=lambda r: r["trades"], reverse=True)

    equity, running = [], 0.0
    for t in trades:
        running += float(t.get("pnl_usdt_net", 0.0))
        equity.append({"time": t.get("time", ""), "equity": round(running, 4),
                       "symbol": t.get("symbol", "")})

    return {
        "overall": _stats(trades),          # current equity period
        "alltime": _stats(all_trades),      # every session log ever written
        "period": period,
        "by_strategy": by_strategy,
        "by_symbol": by_symbol,
        "by_exit": by_exit,
        "equity_curve": equity,
        "generated": datetime.utcnow().isoformat(),
    }



